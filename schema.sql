-- SIPINJAM database schema (jalankan di Supabase SQL Editor)
create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role text not null default 'member' check (role in ('member','admin')),
  created_at timestamptz not null default now()
);

create table public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text,
  created_at timestamptz not null default now()
);

create table public.items (
  id bigint generated by default as identity primary key,
  category_id bigint not null references public.categories(id),
  name text not null,
  description text,
  stock integer not null default 0 check (stock >= 0),
  available_stock integer not null default 0 check (available_stock >= 0 and available_stock <= stock),
  created_at timestamptz not null default now()
);

create table public.loans (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id),
  loan_date date not null default current_date,
  due_date date,
  status text not null default 'pending' check (status in ('pending','approved','rejected','returned')),
  notes text,
  created_at timestamptz not null default now(),
  check (due_date is null or due_date >= loan_date)
);

create table public.loan_items (
  id bigint generated by default as identity primary key,
  loan_id bigint not null references public.loans(id) on delete cascade,
  item_id bigint not null references public.items(id),
  quantity integer not null check (quantity > 0),
  unique (loan_id,item_id)
);

-- Buat profile otomatis saat user mendaftar lewat Supabase Auth.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into public.profiles(id,full_name)
  values(new.id,coalesce(new.raw_user_meta_data->>'full_name','Pengguna Baru'));
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

-- RLS: user yang login dapat melihat inventaris; setiap user hanya melihat/membuat pengajuannya sendiri.
alter table public.profiles enable row level security;
alter table public.categories enable row level security;
alter table public.items enable row level security;
alter table public.loans enable row level security;
alter table public.loan_items enable row level security;

create policy "profile read own" on public.profiles for select to authenticated using (id=auth.uid());
create policy "profile update own" on public.profiles for update to authenticated using (id=auth.uid()) with check (id=auth.uid());
create policy "categories read authenticated" on public.categories for select to authenticated using (true);
create policy "items read authenticated" on public.items for select to authenticated using (true);
create policy "loans read own" on public.loans for select to authenticated using (user_id=auth.uid());
create policy "loans insert own" on public.loans for insert to authenticated with check (user_id=auth.uid());
create policy "loans delete own pending" on public.loans for delete to authenticated using (user_id=auth.uid() and status='pending');
create policy "loan items read own" on public.loan_items for select to authenticated using (
  exists(select 1 from public.loans l where l.id=loan_id and l.user_id=auth.uid())
);
create policy "loan items insert own" on public.loan_items for insert to authenticated with check (
  exists(select 1 from public.loans l where l.id=loan_id and l.user_id=auth.uid() and l.status='pending')
);

